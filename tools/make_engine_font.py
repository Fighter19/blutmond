INK = (255, 255, 255, 255)
SHADOW = (40, 40, 48, 255)


def main():
    out = sys.argv[1]
    first, last = 32, 126
    count = last - first + 1
    columns = 16
    rows = (count + columns - 1) // columns
    img = Image.new("RGBA", (columns * 8, rows * 8), (0, 0, 0, 0))
    for code in range(first, last + 1):
        glyph = GLYPHS[chr(code)]
        assert len(glyph) == 7 and all(len(r) == 5 for r in glyph), chr(code)
        i = code - first
        ox, oy = (i % columns) * 8 + 1, (i // columns) * 8
        ink = {(x, y) for y in range(7) for x in range(5) if glyph[y][x] == '#'}
        for x, y in ink:
            img.putpixel((ox + x, oy + y), INK)
        for x, y in ink:
            sx, sy = x + 1, y + 1
            if (sx, sy) not in ink:
                img.putpixel((ox + sx, oy + sy), SHADOW)
    img.save(os.path.join(out, "font.png"))
    with open(os.path.join(out, "font.bmfont"), "w") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        f.write('<font version="1" image="font.png" cell_w="8" cell_h="8" first="%d" count="%d"/>\n' % (first, count))


if __name__ == "__main__":
    main()
