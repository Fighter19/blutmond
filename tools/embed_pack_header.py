"""Writes a cooked pack as a C array (a header), or checks that a header holds that pack.

usage: embed_pack_header.py <pack.bmpk> <header.h> <array name> [--check]

The game keeps the engine's font this way (apps/game/builtin_font.h): a pack of its own that the
loading box draws with while no other pack is there. --check fails if the header is not what
the pack gives (a test keeps it up to date with the cooker).
"""
import sys


def header(data, name):
    lines = ["// Generated by tools/embed_pack_header.py from a cooked pack: do not edit.",
             "#pragma once", "", "#include <stdint.h>", "",
             "static const uint8_t %s[%d] __attribute__((aligned(4))) = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    data = open(sys.argv[1], "rb").read()
    text = header(data, sys.argv[3])
    if "--check" in sys.argv[4:]:
        current = open(sys.argv[2]).read()
        if current != text:
            print("%s is not what %s gives: run tools/embed_pack_header.py again" % (sys.argv[2], sys.argv[1]))
            return 1
        return 0
    with open(sys.argv[2], "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
